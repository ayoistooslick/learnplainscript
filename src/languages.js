export function findLanguage(code) {
  if (!code) return LANGUAGES.find((item) => item.code === DEFAULT_LANGUAGE);
  const exact = LANGUAGES.find((item) => item.code.toLowerCase() === String(code).toLowerCase());
  if (exact) return exact;
  const base = String(code).toLowerCase().split('-')[0];
  return LANGUAGES.find((item) => item.code.toLowerCase() === base)
    || LANGUAGES.find((item) => item.code === DEFAULT_LANGUAGE);
}

export function savedLanguage() {
  try {
    const code = window.localStorage.getItem(LANGUAGE_KEY);
    if (code) return findLanguage(code);
  } catch {
    // A reading preference is optional; private browsing can refuse storage.
  }
  return findLanguage(document.documentElement.lang);
}
