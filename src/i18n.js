export const TRANSLATED_CODES = Object.keys(TRANSLATIONS);

function interpolate(text, vars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
  ));
}

export function translate(code, text, vars) {
  const table = TRANSLATIONS[code];
  const copy = (table && table[text]) || text;
  return interpolate(copy, vars);
}

export function hasTranslation(code) {
  return Boolean(code && TRANSLATIONS[code]);
}

const I18nContext = createContext('en');

export function I18nProvider({ language, children }) {
  const value = language?.code || 'en';
  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useT() {
  const code = useContext(I18nContext);
  return useMemo(() => (text, vars) => translate(code, text, vars), [code]);
}
